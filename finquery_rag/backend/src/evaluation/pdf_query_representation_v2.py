"""Gold-independent financial concept resolution for PDF query representation V2."""

from __future__ import annotations

from collections import Counter
from hashlib import sha256
import math
import re
from typing import Iterable


TOKEN_RE = re.compile(r"[a-z0-9]+")
MODIFIERS = {"total", "net", "consolidated", "other", "current"}
FAMILY_RULES = (
    ("cash_flow", {"cash", "operating", "activities"}),
    ("revenue", {"revenue", "revenues", "sales"}),
    ("income", {"income", "profit", "earnings"}),
    ("assets", {"asset", "assets"}),
    ("liabilities", {"liability", "liabilities", "debt"}),
    ("equity", {"equity", "stockholders", "shareholders"}),
    ("receivables", {"receivable", "receivables"}),
    ("expenses", {"expense", "expenses", "cost", "costs"}),
)
GENERIC_ALIAS_RULES = (
    (re.compile(r"\bnet cash provided by operating activities\b"), "cash generated by normal operations"),
    (re.compile(r"\bnet cash (?:used in|provided by) investing activities\b"), "cash flow from investing"),
    (re.compile(r"\bnet cash (?:used in|provided by) financing activities\b"), "cash flow from financing"),
    (re.compile(r"\btotal revenues?\b"), "company revenue"),
    (re.compile(r"\bnet sales\b"), "money made from sales"),
    (re.compile(r"\bnet income\b"), "bottom line profit"),
    (re.compile(r"\bgross profit\b"), "profit after direct costs"),
    (re.compile(r"\baccounts? receivable\b"), "money owed by customers"),
    (re.compile(r"\btotal assets\b"), "company asset base"),
    (re.compile(r"\btotal liabilities\b"), "company obligations"),
)


def normalize_label(value: str) -> str:
    value = value.casefold().replace("’", "'")
    value = re.sub(r"\.{2,}", " ", value)
    value = re.sub(r"\([^)]*\d[^)]*\)", " ", value)
    return " ".join(TOKEN_RE.findall(value))


def tokens(value: str) -> tuple[str, ...]:
    return tuple(TOKEN_RE.findall(normalize_label(value)))


def concept_family(value: str) -> str:
    terms = set(tokens(value))
    scored = [(len(terms & clues), family) for family, clues in FAMILY_RULES]
    score, family = max(scored, default=(0, "other"))
    return family if score else "other"


def canonical_key(value: str) -> str:
    terms = [term for term in tokens(value) if term not in MODIFIERS]
    if not terms:
        terms = list(tokens(value))
    family = concept_family(value)
    return f"{family}:{' '.join(terms)}"


def stable_id(namespace: str, *parts: object) -> str:
    payload = "|".join([namespace, *map(str, parts)])
    return f"{namespace}:{sha256(payload.encode()).hexdigest()}"


def char_ngrams(value: str, size: int = 3) -> set[str]:
    text = f"  {normalize_label(value)}  "
    return {text[index : index + size] for index in range(max(0, len(text) - size + 1))}


def char_score(left: str, right: str) -> float:
    a, b = char_ngrams(left), char_ngrams(right)
    return len(a & b) / len(a | b) if a and b else 0.0


def token_bm25_scores(query: str, documents: list[str], k1: float = 1.2, b: float = 0.75) -> list[float]:
    corpus = [tokens(document) for document in documents]
    query_terms = tokens(query)
    avgdl = sum(map(len, corpus)) / max(1, len(corpus))
    document_frequency = Counter(term for terms in corpus for term in set(terms))
    scores = []
    for terms in corpus:
        frequencies = Counter(terms)
        score = 0.0
        for term in query_terms:
            frequency = frequencies[term]
            if not frequency:
                continue
            inverse = math.log(1 + (len(corpus) - document_frequency[term] + 0.5) / (document_frequency[term] + 0.5))
            score += inverse * frequency * (k1 + 1) / (frequency + k1 * (1 - b + b * len(terms) / max(avgdl, 1)))
        scores.append(score)
    return scores


def ranks(scores: Iterable[float]) -> list[int]:
    values = list(scores)
    order = sorted(range(len(values)), key=lambda index: (-values[index], index))
    result = [0] * len(values)
    for rank, index in enumerate(order, 1):
        result[index] = rank
    return result


def fixed_rrf(rank_lists: Iterable[list[int]], k: int = 60) -> list[float]:
    lists = list(rank_lists)
    return [sum(1 / (k + ranking[index]) for ranking in lists) for index in range(len(lists[0]))]


def natural_phrase(label: str, variant: int) -> tuple[str, str]:
    """Return a generic natural phrase without issuer-specific aliases."""
    normalized = normalize_label(label)
    for pattern, phrase in GENERIC_ALIAS_RULES:
        if pattern.search(normalized):
            return phrase, "generic_financial_alias"
    shortened = " ".join(term for term in normalized.split() if term not in MODIFIERS)
    return (shortened or normalized), "generic_modifier_elision"


def generic_aliases(label: str) -> tuple[str, ...]:
    normalized = normalize_label(label)
    return tuple(phrase for pattern, phrase in GENERIC_ALIAS_RULES if pattern.search(normalized))
