"""Unit tests for DocumentHierarchyTree indexing, navigation, and pruning."""

from src.pdf_retrieval_v4.document_tree import DocumentHierarchyTree


def test_tree_construction_and_indexing() -> None:
    tree = DocumentHierarchyTree(doc_id="AAPL-2024-10K")

    # Index 10 mock chunks distributed across filing
    tree.index_chunk("chk_ops_1", {"title": "Consolidated Statements of Operations", "statement_type": "income_statement", "text": "Net sales $391,035"})
    tree.index_chunk("chk_ops_2", {"title": "Consolidated Statements of Operations", "statement_type": "income_statement", "text": "Cost of sales $220,960"})
    tree.index_chunk("chk_bs_1", {"title": "Consolidated Balance Sheets", "statement_type": "balance_sheet", "text": "Total assets $364,980"})
    tree.index_chunk("chk_cf_1", {"title": "Consolidated Statements of Cash Flows", "statement_type": "cash_flow", "text": "Cash generated by operating activities"})
    tree.index_chunk("chk_note19_1", {"title": "Note 19 - Segment Information and Geographic Data", "text": "Services revenue $85,200"})
    tree.index_chunk("chk_note12_1", {"title": "Note 12 - Debt", "text": "Term loan obligations"})
    tree.index_chunk("chk_mda_1", {"section": "Item 7", "title": "Management's Discussion and Analysis", "text": "Gross margin expanded due to services mix"})
    tree.index_chunk("chk_mda_2", {"section": "Item 7", "title": "MD&A Results of Operations", "text": "Foreign exchange rate impacts"})
    tree.index_chunk("chk_risk_1", {"section": "Item 1A", "title": "Risk Factors", "text": "Global supply chain disruptions"})
    tree.index_chunk("chk_biz_1", {"section": "Item 1", "title": "Business", "text": "Company designs, manufactures and markets smartphones"})

    assert tree.total_chunks == 10

    # Prune for Operations statement
    ops_chunks = tree.prune(section_hint="Consolidated Statements of Operations")
    assert ops_chunks == ["chk_ops_1", "chk_ops_2"]
    assert tree.pruning_ratio(ops_chunks) == 0.8  # 80% pruned away!

    # Prune for Balance Sheet
    bs_chunks = tree.prune(statement_type="balance_sheet")
    assert bs_chunks == ["chk_bs_1"]
    assert tree.pruning_ratio(bs_chunks) == 0.9  # 90% pruned away!

    # Prune for Note 19
    note19_chunks = tree.prune(section_hint="Item 8. Note 19 - Segment Information")
    assert note19_chunks == ["chk_note19_1"]

    # Prune for MD&A (even if section hint mentions operations)
    mda_chunks = tree.prune(section_hint="Item 7. MD&A Results of Operations")
    assert mda_chunks == ["chk_mda_1", "chk_mda_2"]

    # Fallback when section_hint is unrecognized returns all chunks
    fallback_chunks = tree.prune(section_hint="Unknown Non-Existent Section")
    assert len(fallback_chunks) == 10
    assert tree.pruning_ratio(fallback_chunks) == 0.0

    # Test empty tree
    empty_tree = DocumentHierarchyTree(doc_id="EMPTY")
    assert empty_tree.total_chunks == 0
    assert empty_tree.prune(section_hint="Item 8") == []
    assert empty_tree.pruning_ratio([]) == 0.0
