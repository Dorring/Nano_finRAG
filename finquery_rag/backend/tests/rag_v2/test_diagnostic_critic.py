def test_replanner_uses_critic_diagnosis() -> None:
    state = AdaptiveRAGStateV1.new(
        request_id="req1",
        query="What was Apple's FY2024 total revenue?",
        required_slots=[_slot("s1", "Total Net Sales", period="FY2024")],
    )
    # Simulate candidates having interim data
    state.evidence_packets = [
        {"source_text": "Three months ended March 2024 Q2 sales were $90,753 million", "value": "90753", "period": "Q2 2024"}
    ]

    eval_result = EvidenceEvaluationV1(
        decision=EvidenceDecision.REPAIRABLE,
        reason_codes=(ReasonCode.MISSING_SLOT,),
        requested_slots=("s1",),
        supported_slots=(),
        missing_slots=("s1",),
    )

    replanner = BoundedReplannerV1(critic=DiagnosticCritic)
    action = replanner.replan(state, eval_result)

    assert action is not None
    assert "annual consolidated" in action.query.lower()
    assert "critic_diagnosis" in action.constraints
    assert action.constraints["critic_diagnosis"]["category"] == CriticDiagnosisCategory.QUARTERLY_VS_ANNUAL.value
    assert action.constraints["section_hint"] == "Item 8. Consolidated Statements of Operations"


