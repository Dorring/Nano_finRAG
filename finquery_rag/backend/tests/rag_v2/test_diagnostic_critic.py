"""Unit tests for DiagnosticCritic fine-grained failure diagnosis and query repair."""

from rag_v2.adaptive.adaptive_contracts import (
    AdaptiveRAGStateV1,
    EvidenceDecision,
    EvidenceEvaluationV1,
    ReasonCode,
)
from rag_v2.adaptive.adaptive_replanner import BoundedReplannerV1
from rag_v2.adaptive.diagnostic_critic import (
    CriticDiagnosisCategory,
    DiagnosticCritic,
)


def _slot(slot_id: str, metric: str, period: str = "FY2024", entity: str = "Apple", scope: str = "consolidated") -> dict:
    return {
        "slot_id": slot_id,
        "metric": metric,
        "period": period,
        "entity": entity,
        "scope": scope,
        "role": "value",
        "value_type": "numeric",
    }


def test_diagnose_quarterly_vs_annual() -> None:
    slot = _slot("s1", "Total Net Sales", period="FY2024")
    candidates = [
        {"source_text": "Net sales for the three months ended March 30, 2024 were $90,753 million (Q2)", "value": "90753", "period": "Q2 2024"},
        {"source_text": "First quarter net sales were $119,575 million (Q1)", "value": "119575", "period": "Q1 2024"},
    ]

    diag = DiagnosticCritic.diagnose_slot(slot, candidates)
    assert diag is not None
    assert diag.category is CriticDiagnosisCategory.QUARTERLY_VS_ANNUAL
    assert "annual consolidated" in diag.suggested_query.lower()
    assert diag.structural_constraints.get("period_semantics") == "annual"


